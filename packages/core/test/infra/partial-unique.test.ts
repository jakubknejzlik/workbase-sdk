import { DatabaseSync } from 'node:sqlite'
import { expect, it } from 'vitest'
import { defineEntity, defineConfig, bindSchemaLock } from '../../src/schema'
import { defineInstance } from '../../src/config'
import { schemaLock, parseLock, lockBytes, checkSchema } from '../../src/migrations/schema-lock'
import { plan, checkLinkage } from '../../src/migrations/schema-plan'
import { parseBundle } from '../../src/migrations/schema-bundle'
import { initialSchema } from '../../src/migrations/schema'
import { plan as legacyPlan } from '../../src/migrations/planner'

const fields = { slot: { type: 'text' as const }, status: { type: 'enum' as const, values: ['confirmed', 'cancelled'] } }
const where = { field: 'status', op: 'eq' as const, value: 'confirmed' }
const unique = { kind: 'unique' as const, name: 'booking_slot_unique', fields: ['slot'] }
const partial = { ...unique, where }
const config = (constraints: unknown[] = [partial]) => {
  const authored = defineConfig({ id: 'partial_constraints', roles: ['owner'], organizationOwnerRole: 'owner', languages: ['en'], entities: {
    booking: defineEntity({ fields, displayField: 'slot', constraints: constraints as any }),
  } })
  return bindSchemaLock(authored, schemaLock(authored))
}

it.each([
  [{ field: 'missing', op: 'eq', value: 'confirmed' }, 'Unknown predicate field'],
  [{ field: 'id', op: 'eq', value: 'id' }, 'Unknown predicate field'],
  [{ ...where, value: 1 }, 'type-compatible'],
  [{ ...where, value: 'unknown' }, 'type-compatible'],
  [{ ...where, value: null }, ''],
  [{ ...where, value: 'confirmed\u0000' }, ''],
  [{ ...where, op: 'ne' }, ''],
  [{ ...where, sql: '1=1' }, ''],
  ['status = \'confirmed\'', ''],
])('rejects invalid typed and raw predicates %j', (where, message) => {
  expect(() => config([{ ...unique, where }])).toThrow(message || undefined)
})
it('validates scalar predicate literals and stored fields at declaration and normalized config boundaries', () => {
  const typedFields = { text: { type: 'text' as const }, string: { type: 'string' as const }, ref: { type: 'ref' as const, entity: 'booking' }, date: { type: 'datetime' as const }, int: { type: 'int' as const }, float: { type: 'float' as const }, bool: { type: 'bool' as const }, derived: { type: 'text' as const, computed: 'text' } }
  for (const [field, value] of [['text', "O'Brien"], ['string', 'value'], ['ref', 'id'], ['date', '2026-01-01T00:00:00Z'], ['int', 2], ['float', 2.5], ['bool', true]] as const) {
    expect(() => defineEntity({ fields: typedFields, constraints: [{ ...unique, fields: ['text'], where: { field, op: 'eq', value } }] })).not.toThrow()
  }
  for (const [field, value] of [['int', 1.5], ['int', '1'], ['float', true], ['bool', 1], ['text', false], ['derived', 'value']] as const) {
    expect(() => defineEntity({ fields: typedFields, constraints: [{ ...unique, fields: ['text'], where: { field, op: 'eq', value } }] } as any)).toThrow()
  }
  const selected = config()
  expect(() => defineInstance({ ...selected, entities: { ...selected.entities, booking: { ...selected.entities.booking, constraints: [{ ...partial, where: { ...where, value: false } }] } } })).toThrow('type-compatible')
})
it('plans predicate-only changes, hashes their identity, and produces deterministic lock/generated bytes with old locks unchanged', async () => {
  const base = await plan({ config: config([unique]), baseMigrations: {} })
  expect(lockBytes(parseLock(base.lock))).toBe(base.lock)
  expect(parseLock(base.lock).tables[0].constraints).toEqual([unique])
  const input = { baseLock: base.lock, baseMigrations: { [base.bundle!.filename]: base.bundle!.sql } }
  const next = await plan({ ...input, config: config() })
  const repeated = await plan({ ...input, config: config([{ where: { value: 'confirmed', op: 'eq', field: 'status' }, fields: ['slot'], name: unique.name, kind: 'unique' }]) })
  expect(next).toEqual(repeated)
  const generated = parseBundle(next.bundle!.filename, next.bundle!.sql).generated
  expect(generated).toMatch(/^DROP INDEX/)
  expect(generated).toContain('WHERE "status" = \'confirmed\'')
  expect(generated).not.toMatch(/CREATE TABLE|DROP TABLE/)
  const db = new DatabaseSync(':memory:')
  try {
    db.exec(initialSchema(config([unique])))
    db.exec(generated)
    const shape = () => db.prepare("SELECT type,name,sql FROM sqlite_schema WHERE tbl_name='booking' ORDER BY type,name").all()
    const replay = shape()
    db.exec('DROP TABLE booking'); db.exec(initialSchema(config()))
    expect(shape()).toEqual(replay)
  } finally { db.close() }
  const legacy = legacyPlan(config([unique]), defineInstance({ ...config(), revision: 2 }))
  expect(legacy.blocked).toEqual([])
  expect(legacy.sql).toContain(generated.trim())
  expect(next.lock).not.toBe(base.lock)
  expect(parseLock(next.lock)).toMatchObject({ revision: 2, tables: [expect.objectContaining({ constraints: [partial] })] })
  expect(lockBytes(parseLock(next.lock))).toBe(next.lock)
  expect(() => checkSchema(config(), parseLock(base.lock))).toThrow('schema differs')
  await checkLinkage(base.lock, input.baseMigrations, next.lock, { ...input.baseMigrations, [next.bundle!.filename]: next.bundle!.sql })
  const changed = await plan({ ...input, config: config([{ ...partial, where: { ...where, value: 'cancelled' } }]) })
  expect(changed.lock).not.toBe(next.lock)
  expect(changed.bundle!.sql).not.toBe(next.bundle!.sql)
  const removed = await plan({ baseLock: next.lock, baseMigrations: { ...input.baseMigrations, [next.bundle!.filename]: next.bundle!.sql }, config: config([unique]) })
  expect(parseBundle(removed.bundle!.filename, removed.bundle!.sql).generated).not.toContain('WHERE')
})
it('rejects existing confirmed duplicates without cleanup; replay r1 to r2 equals a fresh partial schema', async () => {
  const base = await plan({ config: config([]), baseMigrations: {} })
  const next = await plan({ config: config(), baseLock: base.lock, baseMigrations: { [base.bundle!.filename]: base.bundle!.sql } })
  const db = new DatabaseSync(':memory:')
  try {
    db.exec("CREATE TABLE organizations (id TEXT PRIMARY KEY); INSERT INTO organizations VALUES ('a'),('b');")
    db.exec(initialSchema(config([])))
    db.exec("INSERT INTO booking (id,organization_id,slot,status,created_at,updated_at) VALUES ('one','a','s','confirmed','now','now'),('two','a','s','confirmed','now','now')")
    const sql = parseBundle(next.bundle!.filename, next.bundle!.sql).generated
    expect(() => db.exec(sql)).toThrow('UNIQUE constraint failed')
    expect(db.prepare('SELECT count(*) AS n FROM booking').get()).toEqual({ n: 2 })
    db.exec("UPDATE booking SET status='cancelled' WHERE id='two'")
    db.exec(sql)
    const shape = () => db.prepare("SELECT type,name,sql FROM sqlite_schema WHERE tbl_name='booking' ORDER BY type,name").all()
    const replay = shape()
    db.exec('DROP TABLE booking'); db.exec(initialSchema(config()))
    expect(shape()).toEqual(replay)
  } finally { db.close() }
})
it('quotes predicate literals, rejects malformed locks, and safely rejects constrained rebuilds/renames', async () => {
  const selected = config()
  const lock = schemaLock(selected)
  for (const where of [{ ...partial.where, field: 'missing' }, { ...partial.where, value: 1 }, { ...partial.where, op: 'raw' }, '1=1']) {
    expect(() => parseLock(JSON.stringify({ ...lock, tables: [{ ...lock.tables[0], constraints: [{ ...partial, where }] }] }))).toThrow('Invalid schema.lock.json')
  }
  const quoted = defineInstance({ ...selected, entities: { ...selected.entities, booking: { ...selected.entities.booking, fields: { slot: { type: 'text' }, status: { type: 'text' } }, constraints: [{ ...partial, where: { ...where, value: "confirmed'; DROP TABLE booking; --" } }] } } })
  expect(initialSchema(quoted)).toContain("WHERE \"status\" = 'confirmed''; DROP TABLE booking; --'")
  const rebuilt = defineInstance({ ...selected, revision: 2, entities: { ...selected.entities, booking: { ...selected.entities.booking, fields: { ...selected.entities.booking.fields, extra: { type: 'ref', entity: 'booking' } } } } })
  expect(legacyPlan(selected, rebuilt).blocked.join(' ')).toContain('Rebuilding a constrained table')
  const renamed = defineInstance({ ...selected, entities: { ...selected.entities, booking: { ...selected.entities.booking, fields: { slot: fields.slot, state: { ...fields.status, renameFrom: 'status' } }, constraints: [{ ...partial, where: { ...where, field: 'state' } }] } } })
  expect(schemaLock(renamed, lock).tables[0].constraints).toEqual([partial])
  const base = await plan({ config: selected, baseMigrations: {} })
  await expect(plan({ config: renamed, baseLock: base.lock, baseMigrations: { [base.bundle!.filename]: base.bundle!.sql } })).rejects.toThrow('expansion SQL is unsupported')
})
