// Uses the pinned library's own schema compiler, with Bun's built-in SQLite.
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { Database } from 'bun:sqlite'
import { getMigrations } from 'better-auth/db/migration'
import { createIdentityAuth } from './src/better-auth.ts'
const auth = createIdentityAuth({ IDENTITY: { baseURL: 'https://workbase.example', secret: 'schema-generation-only-secret-32-characters' } }, undefined)
const plan = await getMigrations({ ...auth.options, database: new Database(':memory:') })
const generated = await plan.compileMigrations()
const suffix = `
-- Workbase compatibility projection preserves all existing foreign keys and IDs.
INSERT INTO "user" (id,name,email,"emailVerified","createdAt","updatedAt")
  SELECT id,'',lower(email),0,strftime('%Y-%m-%dT%H:%M:%fZ',created_at),strftime('%Y-%m-%dT%H:%M:%fZ',created_at) FROM users;
-- Existing PBKDF2 credentials and sessions are dev/test only. No production fallback.
-- Allow account-scope email intents without inventing an organization.
CREATE TABLE email_outbox_new (id TEXT PRIMARY KEY, organization_id TEXT REFERENCES organizations(id), recipient TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL, created_at TEXT NOT NULL);
INSERT INTO email_outbox_new SELECT * FROM email_outbox;
DROP TABLE email_outbox;
ALTER TABLE email_outbox_new RENAME TO email_outbox;
CREATE TABLE identity_link_grants (state_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), session_id TEXT NOT NULL, expires_at TEXT NOT NULL);
CREATE UNIQUE INDEX identities_issuer_subject_idx ON identities(issuer,subject);
`
const sql = '-- Generated by Better Auth 1.7.1 getMigrations; Workbase additions below.\n' + generated + '\n' + suffix
// Generate reviewable candidates under scratch; never rewrite applied migrations.
const destination = resolve(process.argv[2] ?? '/tmp/codex/identity-state/generated-auth')
await mkdir(destination, { recursive: true })
await writeFile(join(destination, 'better-auth.sql'), sql)
await writeFile(join(destination, 'better-auth-schema.ts'), '// Generated by packages/plugins/local-auth/generate-auth-migration.mjs.\nexport const betterAuthSchema = ' + JSON.stringify(generated + '\n' + suffix.replace(/^--.*$/gm, '').replace(/INSERT INTO "user"[\s\S]*?FROM users;\n/, '')) + '\n')
