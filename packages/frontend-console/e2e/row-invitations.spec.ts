import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import setup, { origin } from './runtime/setup'
let stop: (() => Promise<void>) | undefined
test.beforeAll(async () => { stop = await setup({ worker: 'row-invitations-worker.ts', seed: 'row-invitations-seed.ts' }) })
test.afterAll(async () => { await stop?.() })
test('176b Czech console filters expired invitations, copies, resends and restricts accepted member navigation', async ({ browser, request }) => {
  const owner = await browser.newContext({ baseURL: origin, permissions: ['clipboard-read', 'clipboard-write'], extraHTTPHeaders: { Authorization: 'Bearer row-owner-session' } })
  const recipient = await browser.newContext({ baseURL: origin, extraHTTPHeaders: { Authorization: 'Bearer row-member-session' } })
  const page = await owner.newPage()
  try {
    await page.goto('/o/org-a/e/people/one')
    await expect(page.getByText('Bez účtu', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Pozvat do aplikace', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('E-mail', { exact: true }).fill('member@example.test')
    await dialog.getByRole('button', { name: 'Pozvat do aplikace', exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect(page.getByText('Pozváno', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Kopírovat odkaz', exact: true }).click()
    await dialog.getByRole('button', { name: 'Kopírovat odkaz', exact: true }).click()
    await expect(dialog).toBeHidden()
    const copied = await page.evaluate(() => navigator.clipboard.readText())
    expect(new URL(copied).pathname).toBe('/invitations/accept')
    const token = new URL(copied).searchParams.get('token')!
    expect((await request.post(`${origin}/__test/expire`, { headers: { Authorization: 'Bearer row-local-control' } })).ok()).toBe(true)
    await page.reload()
    await expect(page.getByText('Vypršela', { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Kopírovat odkaz' })).toHaveCount(0)
    const expired = await recipient.request.post('/invitations/accept', { data: { token } })
    expect(expired.status()).toBe(410)
    expect((await expired.json()).error).toBe('invitation_expired')
    await page.goto('/o/org-a/e/people')
    await page.getByLabel('Stav přístupu', { exact: true }).selectOption('expired')
    await expect(page.getByRole('link', { name: 'Lenka', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Petra', exact: true })).toHaveCount(0)
    await expect(page.getByRole('columnheader', { name: 'Přístup do aplikace', exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Stav přístupu', { exact: true })).toHaveValue('expired')
    mkdirSync('/tmp/codex/176-proof/screenshots', { recursive: true })
    await page.screenshot({ path: '/tmp/codex/176-proof/screenshots/expired-filter.png', fullPage: true })
    await page.getByRole('link', { name: 'Lenka', exact: true }).click()
    await page.getByRole('button', { name: 'Znovu odeslat', exact: true }).click()
    await dialog.getByRole('button', { name: 'Znovu odeslat', exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect(page.getByText('Pozváno', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Kopírovat odkaz', exact: true }).click()
    await dialog.getByRole('button', { name: 'Kopírovat odkaz', exact: true }).click()
    await expect(dialog).toBeHidden()
    const fresh = await page.evaluate(() => navigator.clipboard.readText())
    expect(fresh).not.toBe(copied)
    const memberPage = await recipient.newPage()
    await memberPage.goto(fresh)
    await expect(memberPage.getByRole('button', { name: 'Přijmout pozvánku', exact: true })).toBeVisible()
    await memberPage.getByRole('button', { name: 'Přijmout pozvánku', exact: true }).click()
    await memberPage.goto('/o/org-a/e/people')
    await expect(memberPage.getByRole('link', { name: 'Lenka', exact: true })).toBeVisible()
    await expect(memberPage.getByRole('link', { name: 'Petra', exact: true })).toHaveCount(0)
    const nav = memberPage.getByRole('navigation', { name: 'Hlavní navigace', exact: true })
    await expect(nav.getByRole('link', { name: 'Pracovníci', exact: true })).toBeVisible()
    await expect(nav.getByRole('link')).toHaveCount(1)
    await expect(memberPage.getByRole('button', { name: 'Kopírovat odkaz' })).toHaveCount(0)
    await memberPage.screenshot({ path: '/tmp/codex/176-proof/screenshots/member-navigation.png', fullPage: true })
    await memberPage.setViewportSize({ width: 390, height: 844 })
    await expect(memberPage.getByRole('link', { name: 'Lenka', exact: true })).toBeVisible()
    await memberPage.screenshot({ path: '/tmp/codex/176-proof/screenshots/member-mobile.png', fullPage: true })
  } finally { await owner.close(); await recipient.close() }
})
