import { DatabaseSync } from 'node:sqlite'
import { readFile, readdir } from 'node:fs/promises'
import { plan } from '@workbasehq/core/migrations/planner'
import config from '../config'

// Compare the committed SQL chain with the public planner's fresh desired schema.
// Comparing logical metadata permits additive ALTERs and renames with different SQL spelling.
const q = (name: string) => `"${name.replaceAll('"', '""')}"`
function checks(sql: string) {
  // Tokenize literals separately: a default string containing CHECK(...) is data.
  const tokens = sql.match(/'(?:''|[^'])*'|"(?:""|[^"])*"|[a-z_][a-z0-9_]*|[^\s]/gi) ?? []
  const expressions: string[] = []
  for (let i = 0; i < tokens.length; i++) {
    if (tokens[i].toUpperCase() !== 'CHECK' || tokens[i + 1] !== '(') continue
    let depth = 0
    const expression: string[] = []
    for (++i; i < tokens.length; i++) {
      const token = tokens[i]
      expression.push(token.startsWith('"') ? token.slice(1, -1).replaceAll('""', '"') : token)
      if (token === '(') depth++
      if (token === ')' && --depth === 0) break
    }
    expressions.push(expression.join(''))
  }
  return expressions.sort()
}
function snapshot(db: DatabaseSync) {
  const objects = db.prepare("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE type IN ('table','index','trigger') AND name NOT GLOB 'sqlite_*' ORDER BY type,name").all()
  return objects.map(row => ({ type: row.type, name: row.name, table: row.tbl_name,
    ...(row.type === 'table' ? {
      checks: checks(String(row.sql)),
      columns: db.prepare(`PRAGMA table_info(${q(String(row.name))})`).all().map(({ cid: _cid, ...c }) => c).sort((a, b) => String(a.name).localeCompare(String(b.name))),
      foreignKeys: db.prepare(`PRAGMA foreign_key_list(${q(String(row.name))})`).all().map(({ id: _id, ...fk }) => fk).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))),
    } : row.type === 'index' ? {
      columns: db.prepare(`PRAGMA index_info(${q(String(row.name))})`).all().map(({ cid: _cid, ...c }) => c),
      sql: String(row.sql).replaceAll('"', '').replace(/\s+/g, ''),
    } : { sql: row.sql }),
  }))
}
function automaticConstraints(db: DatabaseSync) {
  const tables = db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT GLOB 'sqlite_*'").all()
  return tables.flatMap(table => db.prepare(`PRAGMA index_list(${q(String(table.name))})`).all()
    .filter(index => index.unique === 1 && ['u', 'pk'].includes(String(index.origin)))
    .map(index => JSON.stringify({ table: table.name, origin: index.origin,
      columns: db.prepare(`PRAGMA index_info(${q(String(index.name))})`).all().map(column => column.name),
    }))).sort()
}
function constraintDescription(key: string) {
  const { table, origin, columns } = JSON.parse(key)
  return `${origin === 'pk' ? 'PRIMARY KEY' : 'UNIQUE'} constraint ${table}(${columns.join(', ')})`
}
const actual = new DatabaseSync(':memory:'), desired = new DatabaseSync(':memory:')
try {
  const files = (await readdir('migrations')).filter(name => name !== '.gitkeep').sort()
  if (!files.length || files.some(name => !/^\d{4}_[a-z0-9_]+\.sql$/.test(name))) throw Error('Commit numbered SQL migrations; run migrate:initial once before the MCP loop')
  for (const file of files) actual.exec(await readFile(`migrations/${file}`, 'utf8'))
  const planned = plan(null, config)
  if (planned.blocked.length) throw Error(planned.blocked.join('; '))
  desired.exec(planned.sql)
  // Supplemental indexes are generated by the MCP alongside the public planner SQL.
  let indexes: { name: string; entity: string; fields: string[] }[] = []
  try { indexes = JSON.parse(await readFile('config.indexes.json', 'utf8')) }
  catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error }
  for (const index of indexes) desired.exec(`CREATE INDEX ${q(index.name)} ON ${q(index.entity)} (${['organization_id', ...index.fields].map(q).join(', ')});`)
  // sqlite_autoindex names depend on declaration order; compare their logical constraints.
  const actualConstraints = automaticConstraints(actual), desiredConstraints = automaticConstraints(desired)
  const constraintDiff = [
    ...desiredConstraints.filter(key => !actualConstraints.includes(key)).map(key => `missing ${constraintDescription(key)}`),
    ...actualConstraints.filter(key => !desiredConstraints.includes(key)).map(key => `extra ${constraintDescription(key)}`),
  ]
  if (constraintDiff.length) throw Error(`Pending SQL: ${constraintDiff.join('; ')}`)
  const meta = (db: DatabaseSync) => db.prepare('SELECT revision, core_version FROM instance_meta ORDER BY revision DESC LIMIT 1').get()
  if (JSON.stringify(snapshot(actual)) !== JSON.stringify(snapshot(desired)) || JSON.stringify(meta(actual)) !== JSON.stringify(meta(desired))) {
    throw Error('Pending SQL: config and committed migrations are out of sync. Use inspect → propose → validate → preview → apply_to_disposable → promote, then commit config, history and SQL together.')
  }
  console.log(`Config/migrations in sync (${files.length} SQL files, revision ${config.revision}); no pending SQL`)
} catch (error) {
  console.error(`Migration sync check failed: ${(error as Error).message}`)
  process.exitCode = 1
} finally { actual.close(); desired.close() }
